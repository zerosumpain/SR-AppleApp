#!/usr/bin/env node
// Regenerates ios/SRAppleApp/Offline/Words/offline-words.txt — the word list
// the offline Boggle and Anagram Blitz judge by, bundled with the app.
//
//   node scripts/build-offline-words.mjs ~/path/to/SR-Main
//
// The words are the site's own: SR-Main's src/lib/games/words/anagram.ts
// (three to seven letters, and the seven-letter SEEDS a rack is dealt from)
// and src/lib/games/words/boggle.ts (eight letters and up), cut to three to
// nine letters. Using the same lists means a word the site's Boggle accepts
// is accepted offline too (up to nine letters), and the same words are left
// out — SR-Main took the slurs, sexual and crude words and the drink and drug
// words out of them by hand, so this script has no blocklist of its own.
//
// The file is one word a line, sorted. A COMMON word (one the site may show
// as a word "nobody found") starts with a capital; the rest are accepted but
// never shown. The seeds follow `@seeds`, commonest first. Plain text rather
// than gzip: Foundation on Linux (where the rules' tests run) cannot inflate,
// and the app archive is compressed anyway.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const site = process.argv[2];
if (!site) {
  console.error('usage: node scripts/build-offline-words.mjs <SR-Main checkout>');
  process.exit(2);
}
const OUT = 'ios/SRAppleApp/Offline/Words/offline-words.txt';
const MIN = 3;
const MAX = 9;

/** Every `export const NAME … split(` … `)` list in a words module. */
function lists(path) {
  const source = readFileSync(join(site, path), 'utf8');
  const out = {};
  for (const match of source.matchAll(/export const (\w+)[^=]*=\s*split\(`([^`]*)`\)/g)) {
    out[match[1]] = match[2].trim().split(/\s+/);
  }
  return out;
}

const anagram = lists('src/lib/games/words/anagram.ts');
const boggle = lists('src/lib/games/words/boggle.ts');
for (const name of ['COMMON_WORDS', 'RARE_WORDS', 'SEEDS']) {
  if (!anagram[name]?.length) throw new Error(`anagram.ts has no ${name}`);
}
for (const name of ['LONG_COMMON', 'LONG_RARE']) {
  if (!boggle[name]?.length) throw new Error(`boggle.ts has no ${name}`);
}

const fits = (word) => /^[a-z]+$/.test(word) && word.length >= MIN && word.length <= MAX;
const common = new Set([...anagram.COMMON_WORDS, ...boggle.LONG_COMMON].filter(fits));
const every = new Set([...common, ...anagram.RARE_WORDS.filter(fits), ...boggle.LONG_RARE.filter(fits)]);
// Byte order, which is what the app's binary search compares by.
const sorted = [...every].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
const seeds = anagram.SEEDS.filter((word) => word.length === 7 && common.has(word));

const header = `# Strange Ramblings offline word list: ${sorted.length} words of ${MIN}-${MAX} letters
# (${common.size} common, marked with a capital) and ${seeds.length} seven-letter seeds.
# Generated by scripts/build-offline-words.mjs from SR-Main's games word lists
# (src/lib/games/words/anagram.ts and boggle.ts). Do not edit by hand.
#
# The words come from the Hunspell en_US dictionary, which is built from SCOWL
# (Spell Checker Oriented Word Lists), expanded through its affix rules, with
# British spellings added and offensive words removed by hand. Which words are
# "common" follows how often they are spoken in film and TV subtitles
# (hermitdave/FrequencyWords, 2018 en_50k, from OpenSubtitles).
#
# SCOWL: Copyright 2000-2011 by Kevin Atkinson
#   Permission to use, copy, modify, distribute and sell these word
#   lists, the associated scripts, the output created from the scripts,
#   and its documentation for any purpose is hereby granted without fee,
#   provided that the above copyright notice appears in all copies and
#   that both that copyright notice and this permission notice appear in
#   supporting documentation. Kevin Atkinson makes no representations
#   about the suitability of this array for any purpose. It is provided
#   "as is" without express or implied warranty.
#
# SCOWL's inflections were made with the help of WordNet:
#   WordNet 1.6 Copyright 1997 by Princeton University. All rights reserved.
#   THIS SOFTWARE AND DATABASE IS PROVIDED "AS IS" AND PRINCETON UNIVERSITY
#   MAKES NO REPRESENTATIONS OR WARRANTIES, EXPRESS OR IMPLIED.
# Its other sources (Moby Words II, 12Dicts, Brian Kelk's UK English word
# list) are in the public domain.
`;

const lines = sorted.map((word) => (common.has(word) ? word[0].toUpperCase() + word.slice(1) : word));
const text = `${header}@words\n${lines.join('\n')}\n@seeds\n${seeds.join('\n')}\n`;
writeFileSync(OUT, text);
console.log(`${OUT}: ${sorted.length} words (${common.size} common), ${seeds.length} seeds, ${Buffer.byteLength(text)} bytes`);
